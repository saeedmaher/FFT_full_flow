module Twiddle_ROM_Stage2 (
    input  wire [1:0] addr,

    output reg signed [11:0] w_re,
    output reg signed [11:0] w_im
);

    
    always @(*) begin

        case (addr)

            // -------------------------------------------------
            // Address 0 -> W0
            // 1.0 + j0
            // -------------------------------------------------
            2'd0: begin
                w_re = 12'sb010000000000;   // +1024
                w_im = 12'sb000000000000;   //  0
            end

            // -------------------------------------------------
            // Address 1 -> W2
            // cos(pi/4) - j sin(pi/4)
            //
            // 0.70703125 * 1024 ≈ 724
            // -------------------------------------------------
            2'd1: begin
                w_re = 12'sb001011010100;   // +724
                w_im = 12'sb110100101011;  //  -725
            end

            // -------------------------------------------------
            // Address 2 -> W4
            // 0 - j1
            // -------------------------------------------------
            2'd2: begin
                w_re = 12'sb000000000000;   //  0
                w_im = 12'sb110000000000;   // -1024
            end

            // -------------------------------------------------
            // Address 3 -> W6
            // -cos(pi/4) - j sin(pi/4)
            //
            // ≈ -724 - j724
            // -------------------------------------------------
            2'd3: begin
                w_re = 12'sb110100101011;  //  -7255
                w_im = 12'sb110100101011;  //  -725
            end

            default: begin
                w_re = 12'sd0;
                w_im = 12'sd0;
            end

        endcase

    end

endmodule